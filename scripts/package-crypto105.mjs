// Generic build-time packager for privately prebuilt CRYPTO-105 evidence. It holds no puzzle logic:
// it checks an immutable ZIP against its private attestation and copies both into an ignored,
// server-only module. Without staged input it emits an "unavailable" module so builds still work.
// Input directory: CRYPTO105_EVIDENCE_DIR, else the ignored .evidence.local.json, else the committed
// evidence/crypto-105/. See docs/CRYPTO105.md.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ARCHIVE = "shift-change.zip";
const ATTESTATION = "shift-change.attestation.json";
const FORMAT = "DDC-CRYPTO105-ATTESTATION/1";
const VERSIONS = ["SC-ARTIFACT/1"];
const output = new URL("../lib/server/generated/crypto105-evidence.js", import.meta.url);
const localConfig = new URL("../.evidence.local.json", import.meta.url);
const committedDir = fileURLToPath(new URL("../evidence/crypto-105/", import.meta.url));

function inputDirectory() {
  if (process.env.CRYPTO105_EVIDENCE_DIR) return process.env.CRYPTO105_EVIDENCE_DIR;
  const local = existsSync(localConfig) ? JSON.parse(readFileSync(localConfig, "utf8")).CRYPTO105_EVIDENCE_DIR : undefined;
  if (local) return local;
  if (existsSync(committedDir)) return committedDir;
}

export function packageCrypto105() {
  const dir = inputDirectory();
  let staged = null;
  if (dir) {
    const archivePath = join(dir, ARCHIVE), attestationPath = join(dir, ATTESTATION);
    if (!existsSync(archivePath) || !existsSync(attestationPath))
      throw new Error(`CRYPTO-105: the configured evidence directory must contain ${ARCHIVE} and ${ATTESTATION}.`);
    const bytes = readFileSync(archivePath);
    const attestation = JSON.parse(readFileSync(attestationPath, "utf8"));
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    if (attestation.format !== FORMAT || !VERSIONS.includes(attestation.artifactVersion) || attestation.archive !== ARCHIVE
      || attestation.archiveBytes !== bytes.length || attestation.archiveSha256 !== sha256
      || !/^[0-9a-f]{64}$/.test(attestation.flagCommitment) || bytes.readUInt32LE(0) !== 0x04034b50)
      throw new Error("CRYPTO-105: staged evidence does not match its attestation; regenerate it privately.");
    staged = {artifactVersion: attestation.artifactVersion, archiveSha256: sha256, flagCommitment: attestation.flagCommitment, archiveBase64: bytes.toString("base64")};
  }
  const source = "// GENERATED by scripts/package-crypto105.mjs. Do not edit or commit.\n"
    + "import \"server-only\";\n"
    + `export const crypto105Staged = ${JSON.stringify(staged)};\n`;
  // Rewrite only on change so a running dev server is not reloaded needlessly.
  if (!existsSync(output) || readFileSync(output, "utf8") !== source) writeFileSync(output, source);
  console.log(staged
    ? `CRYPTO-105 evidence staged (${staged.artifactVersion}, ${Buffer.from(staged.archiveBase64, "base64").length} bytes).`
    : "CRYPTO-105 evidence not staged; the challenge reports unavailable.");
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) packageCrypto105();
